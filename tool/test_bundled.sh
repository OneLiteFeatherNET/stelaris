#!/usr/bin/env bash
# Runs the test suite with the test files bundled into a few entry points.
#
# `flutter test` compiles, loads and warms up every test file on its own, which
# costs about two seconds per file - more than all the tests themselves take.
# Bundled into a few files that run in parallel, the suite takes about half the
# time. Each test file becomes a group named after its path, so a failure still
# says which file it is in.
#
# Usage: tool/test_bundled.sh [flutter test arguments]
# The number of bundles is the number of processors, or BUNDLE_SHARDS.
#
# A file with a platform or skip annotation (@TestOn, @OnPlatform, @Skip,
# @Timeout) runs on its own, as a bundle would drop the annotation. @Tags is
# dropped too, so do not use this to run a subset of the tags.
set -euo pipefail

cd "$(dirname "$0")/.."

out=test/_bundle
shards=${BUNDLE_SHARDS:-$(nproc)}

rm -rf "$out"
mkdir -p "$out"
trap 'rm -rf "$out"' EXIT

bundled=()
separate=()
# Largest files first, so the round robin below spreads them evenly.
while IFS= read -r file; do
  if grep -qE '^@(TestOn|OnPlatform|Skip|Timeout)\b' "$file"; then
    separate+=("$file")
  else
    bundled+=("$file")
  fi
done < <(find test -name '*_test.dart' -not -path "$out/*" -printf '%s %p\n' |
  sort -rn | cut -d' ' -f2-)

if ((${#bundled[@]} < shards)); then
  shards=${#bundled[@]}
fi

for ((k = 0; k < shards; k++)); do
  {
    echo "// Generated by tool/test_bundled.sh."
    echo "import 'package:flutter_test/flutter_test.dart';"
    echo
    for ((i = k; i < ${#bundled[@]}; i += shards)); do
      echo "import '../${bundled[i]#test/}' as t$i;"
    done
    echo
    echo "void main() {"
    for ((i = k; i < ${#bundled[@]}; i += shards)); do
      echo "  group('${bundled[i]#test/}', t$i.main);"
    done
    echo "}"
  } >"$out/bundle_${k}_test.dart"
done

flutter test "$@" "$out" "${separate[@]}"
